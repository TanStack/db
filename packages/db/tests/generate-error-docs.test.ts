// Ordinary CLI controls. The existing production-error oracle owns catalog
// judgment; these examples check modes, file effects and malformed inputs.
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { expect, it } from 'vitest'
import {
  withErrorDocsFixture,
  writeErrorDocsExample,
} from './generate-error-docs-fixture'
import type { ErrorDocsFixture } from './generate-error-docs-fixture'

function fulfilled(result: ReturnType<ErrorDocsFixture['run']>): void {
  expect(result.error).toBeUndefined()
  expect(result.status, result.stderr).toBe(0)
}

it(`emits exactly the default generated bytes without stdout from default mode`, () => {
  withErrorDocsFixture((fixture) => {
    writeErrorDocsExample(fixture)
    const generated = fixture.run()
    fulfilled(generated)
    expect(generated.stdout).toBe(``)
    const page = readFileSync(fixture.pagePath, `utf8`)
    for (const value of [
      `## Error 7: \`FixtureError\``,
      `<a id="error-7"></a>`,
      `fixture class message`,
      `## Error 8: \`fixture.ts\``,
      `<a id="error-8"></a>`,
      `fixture failure \${id}`,
      `## Warning 9: \`warning.ts\``,
      `<a id="warning-9"></a>`,
      `fixture warning`,
    ])
      expect(page).toContain(value)
    const printed = fixture.run(`--stdout`)
    fulfilled(printed)
    expect(printed.stdout).toBe(page)
    expect(printed.stderr).toBe(``)
    expect(readFileSync(fixture.pagePath, `utf8`)).toBe(page)
  })
})

it.each([`missing`, `stale`] as const)(
  `stdout leaves a %s page untouched`,
  (state) => {
    withErrorDocsFixture((fixture) => {
      writeErrorDocsExample(fixture)
      if (state === `stale`) writeFileSync(fixture.pagePath, `stale sentinel`)
      const result = fixture.run(`--stdout`)
      fulfilled(result)
      expect(result.stdout).toContain(`fixture class message`)
      expect(result.stderr).toBe(``)
      expect(existsSync(fixture.pagePath)).toBe(state === `stale`)
      if (state === `stale`)
        expect(readFileSync(fixture.pagePath, `utf8`)).toBe(`stale sentinel`)
    })
  },
)

it(`reads current fixtures independently of a stale generated page`, () => {
  withErrorDocsFixture((fixture) => {
    writeErrorDocsExample(fixture, `first catalog message`)
    fulfilled(fixture.run())
    const before = readFileSync(fixture.pagePath, `utf8`)
    writeErrorDocsExample(fixture, `changed catalog message`)
    const result = fixture.run(`--stdout`)
    fulfilled(result)
    expect(result.stdout).toContain(`changed catalog message`)
    expect(result.stdout).not.toContain(`first catalog message`)
    expect(readFileSync(fixture.pagePath, `utf8`)).toBe(before)
  })
})

it(`check accepts matching generated bytes without writing`, () => {
  withErrorDocsFixture((fixture) => {
    writeErrorDocsExample(fixture)
    fulfilled(fixture.run())
    const before = readFileSync(fixture.pagePath)
    const result = fixture.run(`--check`)
    fulfilled(result)
    expect(result.stdout).toBe(``)
    expect(readFileSync(fixture.pagePath)).toEqual(before)
  })
})

it.each([`missing`, `stale`] as const)(
  `check rejects a %s page without writing`,
  (state) => {
    withErrorDocsFixture((fixture) => {
      writeErrorDocsExample(fixture)
      if (state === `stale`) writeFileSync(fixture.pagePath, `stale sentinel`)
      const result = fixture.run(`--check`)
      expect(result.error).toBeUndefined()
      expect(result.status).toBe(1)
      expect(result.stderr).toContain(`docs/errors.md is out of date`)
      expect(result.stdout).toBe(``)
      expect(existsSync(fixture.pagePath)).toBe(state === `stale`)
      if (state === `stale`)
        expect(readFileSync(fixture.pagePath, `utf8`)).toBe(`stale sentinel`)
    })
  },
)

it.each([
  { args: [`--stdout`, `--check`] },
  { args: [`--stdout`, `--stdout`] },
  { args: [`--unknown`] },
  { args: [`unexpected`] },
])(`rejects invalid CLI arguments %j before writing`, ({ args }) => {
  withErrorDocsFixture((fixture) => {
    writeErrorDocsExample(fixture)
    writeFileSync(fixture.pagePath, `stale sentinel`)
    const result = fixture.run(...args)
    expect(result.error).toBeUndefined()
    expect(result.status).toBe(1)
    expect(result.stderr).toContain(`Usage:`)
    expect(result.stdout).toBe(``)
    expect(readFileSync(fixture.pagePath, `utf8`)).toBe(`stale sentinel`)
  })
})

it(`rejects invalid arguments before reading fixtures`, () => {
  withErrorDocsFixture((fixture) => {
    rmSync(join(fixture.fixturesDirectory, `error-codes.json`))
    writeFileSync(fixture.pagePath, `stale sentinel`)
    const result = fixture.run(`--unknown`)
    expect(result.error).toBeUndefined()
    expect(result.status).toBe(1)
    expect(result.stderr).toContain(`Usage:`)
    expect(result.stderr).not.toContain(`ENOENT`)
    expect(readFileSync(fixture.pagePath, `utf8`)).toBe(`stale sentinel`)
  })
})

it.each([`missing`, `malformed`, `missing-message`] as const)(
  `stdout preserves a %s fixture failure`,
  (fault) => {
    withErrorDocsFixture((fixture) => {
      writeErrorDocsExample(fixture)
      writeFileSync(fixture.pagePath, `stale sentinel`)
      const messages = join(fixture.fixturesDirectory, `error-messages.json`)
      if (fault === `missing`) rmSync(messages)
      else writeFileSync(messages, fault === `malformed` ? `{` : `{}`)
      const result = fixture.run(`--stdout`)
      expect(result.error).toBeUndefined()
      expect(result.status).not.toBe(0)
      expect(result.stderr.length).toBeGreaterThan(0)
      expect(result.stdout).toBe(``)
      expect(readFileSync(fixture.pagePath, `utf8`)).toBe(`stale sentinel`)
    })
  },
)
